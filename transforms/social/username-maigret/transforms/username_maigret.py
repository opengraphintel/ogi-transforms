@dataclass(frozen=True)
class SiteDefinition:
    """One data.json site entry with its engine template applied."""

    name: str
    url: str
    url_main: str
    url_subpath: str
    url_probe: str
    check_type: str
    presence_strs: list[str]
    absence_strs: list[str]
    errors: dict[str, str]
    headers: dict[str, str]
    get_params: dict[str, str]
    request_method: str
    request_payload: JsonObject
    request_head_only: bool
    regex_check: str
    ignore_403: bool
    protection: list[str]
    protocol: str
    encoding: str
    disabled: bool
    id_type: str
    tags: list[str]
    engine: str
    alexa_rank: int

    @property
    def is_checkable(self) -> bool:
        if self.check_type not in CHECK_TYPES:
            return False
        # A message check with neither presence nor absence strings would call
        # every reachable page a claimed account.
        return not (
            self.check_type == "message"
            and not self.presence_strs
            and not self.absence_strs
        )


@dataclass(frozen=True)
class SiteSelection:
    sites: list[SiteDefinition]
    protected_skipped: int


@dataclass(frozen=True)
class SiteCheck:
    site: SiteDefinition
    profile_url: str
    status: str
    http_status: int = 0
    reason: str = ""


def _snake(key: str) -> str:
    result: list[str] = []
    for index, char in enumerate(key):
        if char.isupper() and index > 0 and key[index - 1] != "_":
            result.append("_")
        result.append(char.lower())
    return "".join(result)


def _normalize_keys(raw: JsonObject) -> JsonObject:
    """Snake-case top-level keys only.

    Nested keys are data, such as header names and error markers, and stay verbatim.
    """
    normalized: JsonObject = {}
    for key, value in raw.items():
        name = _snake(key)
        name = FIELD_ALIASES.get(name, name)
        existing = normalized.get(name)
        if isinstance(existing, list) and isinstance(value, list):
            normalized[name] = [*existing, *value]
        else:
            normalized[name] = value
    return normalized


def _merge_engine(template: JsonObject, site: JsonObject) -> JsonObject:
    """Apply an engine template the way Maigret does.

    Lists and dicts combine; a scalar the site states itself wins over the template.
    """
    merged: JsonObject = dict(template)
    for key, value in site.items():
        base = merged.get(key)
        if isinstance(value, list) and isinstance(base, list):
            merged[key] = [*value, *base]
        elif isinstance(value, dict) and isinstance(base, dict):
            merged[key] = {**base, **value}
        else:
            merged[key] = value
    return merged


def _as_object(value: JsonValue) -> JsonObject:
    return value if isinstance(value, dict) else {}


def _as_str(value: JsonValue, default: str = "") -> str:
    return value if isinstance(value, str) else default


def _as_int(value: JsonValue, default: int) -> int:
    if isinstance(value, bool):
        return default
    return value if isinstance(value, int) else default


def _as_str_list(value: JsonValue) -> list[str]:
    if not isinstance(value, list):
        return []
    return [item for item in value if isinstance(item, str)]


def _as_str_dict(value: JsonValue) -> dict[str, str]:
    if not isinstance(value, dict):
        return {}
    return {
        key: str(item)
        for key, item in value.items()
        if isinstance(item, (str, int, float))
    }


def build_site(
    name: str, raw: JsonObject, engines: dict[str, JsonObject]
) -> SiteDefinition:
    data = _normalize_keys(raw)
    template = engines.get(_as_str(data.get("engine")))
    if template is not None:
        data = _merge_engine(template, data)

    return SiteDefinition(
        name=name,
        url=_as_str(data.get("url")),
        url_main=_as_str(data.get("url_main")),
        url_subpath=_as_str(data.get("url_subpath")),
        url_probe=_as_str(data.get("url_probe")),
        check_type=_as_str(data.get("check_type"), "message"),
        presence_strs=_as_str_list(data.get("presence_strs")),
        absence_strs=_as_str_list(data.get("absence_strs")),
        errors=_as_str_dict(data.get("errors")),
        headers=_as_str_dict(data.get("headers")),
        get_params=_as_str_dict(data.get("get_params")),
        request_method=_as_str(data.get("request_method")).upper(),
        request_payload=_as_object(data.get("request_payload")),
        request_head_only=data.get("request_head_only") is True,
        regex_check=_as_str(data.get("regex_check")),
        ignore_403=data.get("ignore403") is True,
        protection=_as_str_list(data.get("protection")),
        protocol=_as_str(data.get("protocol")),
        encoding=_as_str(data.get("encoding")),
        disabled=data.get("disabled") is True,
        id_type=_as_str(data.get("type"), "username"),
        tags=[tag.lower() for tag in _as_str_list(data.get("tags"))],
        engine=_as_str(data.get("engine")),
        alexa_rank=_as_int(data.get("alexa_rank"), NO_RANK),
    )


@lru_cache(maxsize=1)
def load_sites(path: Path = DATA_PATH) -> tuple[SiteDefinition, ...]:
    data = _as_object(json.loads(path.read_text(encoding="utf-8")))
    engines = {
        name: _normalize_keys(_as_object(_as_object(engine).get("site")))
        for name, engine in _as_object(data.get("engines")).items()
    }
    return tuple(
        build_site(name, raw, engines)
        for name, raw in _as_object(data.get("sites")).items()
        if isinstance(raw, dict)
    )


def parse_site_tags(raw: str | None) -> frozenset[str]:
    return frozenset(
        part.strip().lower() for part in re.split(r"[,\s]+", raw or "") if part.strip()
    )


def _matches_tags(site: SiteDefinition, tags: frozenset[str]) -> bool:
    return bool(tags.intersection(site.tags)) or site.engine.lower() in tags


def select_sites(
    sites: tuple[SiteDefinition, ...] | list[SiteDefinition],
    *,
    top_sites: int,
    include_disabled: bool,
    include_protected: bool,
    tags: frozenset[str] = frozenset(),
) -> SiteSelection:
    eligible = [
        site
        for site in sites
        if site.id_type == "username"
        and site.url
        and site.is_checkable
        # dns, tor and i2p entries need gateways this HTTP checker does not have.
        and not site.protocol
        and (include_disabled or not site.disabled)
        and (not tags or _matches_tags(site, tags))
    ]
    eligible.sort(key=lambda site: (site.alexa_rank, site.name.lower()))

    selected: list[SiteDefinition] = []
    protected_skipped = 0
    for site in eligible:
        if len(selected) >= top_sites:
            break
        if site.protection and not include_protected:
            protected_skipped += 1
            continue
        selected.append(site)
    return SiteSelection(sites=selected, protected_skipped=protected_skipped)


def render_urls(site: SiteDefinition, username: str) -> tuple[str, str] | None:
    """Return (profile URL, probe URL), or None if the templates are unusable."""
    quoted = quote(username)
    try:
        profile_url = site.url.format(
            urlMain=site.url_main, urlSubpath=site.url_subpath, username=quoted
        )
        probe_url = (
            site.url_probe.format(
                urlMain=site.url_main, urlSubpath=site.url_subpath, username=quoted
            )
            if site.url_probe
            else ""
        )
    except (KeyError, IndexError, ValueError):
        return None

    profile_url = re.sub(r"(?<!:)/+", "/", profile_url)
    probe_url = probe_url or profile_url
    if site.get_params:
        separator = "&" if "?" in probe_url else "?"
        probe_url = f"{probe_url}{separator}{urlencode(site.get_params)}"
    return profile_url, probe_url


@lru_cache(maxsize=512)
def _compiled_regex(pattern: str) -> re.Pattern[str] | None:
    try:
        return re.compile(pattern)
    except re.error:
        return None


def username_allowed(site: SiteDefinition, username: str) -> bool:
    if not site.regex_check:
        return True
    regex = _compiled_regex(site.regex_check)
    return regex is not None and regex.search(username) is not None


def request_method(site: SiteDefinition) -> str:
    if site.request_method in {"GET", "POST", "HEAD"}:
        return site.request_method
    if site.check_type == "status_code" and site.request_head_only:
        return "HEAD"
    return "GET"


def request_payload(site: SiteDefinition, username: str) -> JsonObject | None:
    """Fill the POST body template; None if it cannot be filled.

    Uses str.format like Maigret, since templates such as GraphQL queries escape
    braces as {{ }}.
    """
    try:
        return {
            key: value.format(username=username) if isinstance(value, str) else value
            for key, value in site.request_payload.items()
        }
    except (KeyError, IndexError, ValueError):
        return None


def detect_error(site: SiteDefinition, status_code: int, body: str) -> str:
    """Mirror Maigret's detect_error_page.

    A refused or challenged request is never evidence either way.
    """
    if body:
        for marker, message in site.errors.items():
            if marker in body:
                return f"Site-specific: {message}"
        for marker, kind in COMMON_ERROR_MARKERS.items():
            if marker in body:
                return kind
    if status_code == 403 and not site.ignore_403:
        return "Access denied"
    if status_code == 401:
        return "Login required"
    if status_code == 429:
        return "Rate limited"
    if status_code == 999:
        return "Access denied"
    if status_code >= 500:
        return "Server error"
    return ""


def evaluate_response(
    site: SiteDefinition, status_code: int, body: str
) -> tuple[str, str]:
    error = detect_error(site, status_code, body)
    if error:
        return UNKNOWN, error

    is_success = 200 <= status_code < 300
    presence_detected = bool(body) and (
        not site.presence_strs or any(flag in body for flag in site.presence_strs)
    )
    if site.check_type == "message":
        # Stricter than Maigret, which ignores the status here: once a site moves
        # its profile URLs, a generic 404 page lacks the absence strings and every
        # username would read as claimed.
        if status_code in MISSING_STATUSES:
            return AVAILABLE, ""
        absence_detected = any(flag in body for flag in site.absence_strs)
        return (
            CLAIMED if presence_detected and not absence_detected else AVAILABLE
        ), ""
    if site.check_type == "status_code":
        return (CLAIMED if is_success else AVAILABLE), ""
    if site.check_type == "response_url":
        return (CLAIMED if is_success and presence_detected else AVAILABLE), ""
    return UNKNOWN, f"Unsupported check type {site.check_type}"


def _decode_body(response: httpx.Response, site: SiteDefinition, method: str) -> str:
    if method == "HEAD":
        return ""
    if site.encoding:
        try:
            return response.content.decode(site.encoding, errors="replace")
        except LookupError:
            pass
    return response.text


class UsernameMaigret(BaseTransform):
    name = "username_maigret"
    display_name = "Username OSINT (Maigret Adoption)"
    description = (
        "Finds claimed usernames using an OGI-native checker with a vendored "
        "Maigret site database"
    )
    input_types = [EntityType.SOCIAL_MEDIA, EntityType.PERSON, EntityType.USERNAME]
    output_types = [EntityType.SOCIAL_MEDIA, EntityType.URL]
    category = "Social Media"
    settings = [
        TransformSetting(
            name="top_sites",
            display_name="Top Sites",
            description=(
                "Maximum number of ranked sites from the vendored Maigret database "
                "to query"
            ),
            default="200",
            field_type="integer",
            min_value=10,
            max_value=1000,
        ),
        TransformSetting(
            name="site_tags",
            display_name="Site Tags",
            description=(
                "Comma-separated Maigret tags or engine names to scan instead of "
                "the most popular sites, e.g. forum, wiki, de, Discourse. A site "
                "matches if it has any of them."
            ),
            default="",
            field_type="string",
            pattern=SITE_TAGS_RE,
        ),
        TransformSetting(
            name="include_disabled_sites",
            display_name="Include Disabled Sites",
            description=(
                "Include sites that the vendored Maigret database marks as disabled"
            ),
            default="false",
            field_type="boolean",
        ),
        TransformSetting(
            name="include_protected_sites",
            display_name="Include Protected Sites",
            description=(
                "Also probe sites Maigret marks as behind bot protection (TLS "
                "fingerprinting, Cloudflare challenges, IP reputation). A plain "
                "HTTP client is usually refused there, and refusals are reported "
                "as unknown"
            ),
            default="false",
            field_type="boolean",
        ),
        TransformSetting(
            name="timeout_seconds",
            display_name="Timeout Seconds",
            description="Per-request timeout used by the adoption checker",
            default="15",
            field_type="integer",
            min_value=3,
            max_value=60,
        ),
        TransformSetting(
            name="max_results",
            display_name="Max Results",
            description="Maximum number of claimed accounts to return",
            default="100",
            field_type="integer",
            min_value=1,
            max_value=500,
        ),
        TransformSetting(
            name="concurrency",
            display_name="Concurrency",
            description="Maximum concurrent site checks",
            default="20",
            field_type="integer",
            min_value=1,
            max_value=50,
        ),
    ]

    async def run(self, entity: Entity, config: TransformConfig) -> TransformResult:
        username = self._normalize_input(entity)
        if not username:
            return TransformResult(
                messages=[
                    "Input value did not contain a usable username candidate.",
                    "Prefer feeding this transform from person_to_usernames "
                    "or a known handle.",
                ]
            )

        top_sites = self.parse_int_setting(
            config.settings.get("top_sites", "200"),
            setting_name="top_sites",
            default=200,
            min_value=10,
            declared_max=1000,
        )
        timeout_seconds = self.parse_int_setting(
            config.settings.get("timeout_seconds", "15"),
            setting_name="timeout_seconds",
            default=15,
            min_value=3,
            declared_max=60,
        )
        max_results = self.parse_int_setting(
            config.settings.get("max_results", "100"),
            setting_name="max_results",
            default=100,
            min_value=1,
            declared_max=500,
        )
        concurrency = self.parse_int_setting(
            config.settings.get("concurrency", "20"),
            setting_name="concurrency",
            default=20,
            min_value=1,
            declared_max=50,
        )
        tags = parse_site_tags(config.settings.get("site_tags", ""))

        try:
            selection = select_sites(
                self._site_database(),
                top_sites=top_sites,
                include_disabled=self._parse_bool(
                    config.settings.get("include_disabled_sites", "false"), False
                ),
                include_protected=self._parse_bool(
                    config.settings.get("include_protected_sites", "false"), False
                ),
                tags=tags,
            )
        except (OSError, ValueError) as exc:
            return TransformResult(
                messages=[f"Failed to load vendored Maigret database: {exc}"]
            )

        scope = f"tags: {', '.join(sorted(tags))}" if tags else "most popular first"
        messages = [
            f"Scanning username '{username}' against {len(selection.sites)} sites "
            f"from the Maigret {MAIGRET_VERSION} database ({scope}, "
            f"concurrency={concurrency})."
        ]
        if selection.protected_skipped:
            messages.append(
                f"Skipped {selection.protected_skipped} bot-protected sites a plain "
                "HTTP client cannot check; enable include_protected_sites to try "
                "them anyway."
            )
        if not selection.sites:
            messages.append("No sites in the Maigret database match these settings.")
            return TransformResult(messages=messages)

        try:
            checks = await self._scan_sites(
                username,
                selection.sites,
                timeout_seconds=timeout_seconds,
                concurrency=concurrency,
            )
        except Exception as exc:
            return TransformResult(
                messages=[*messages, f"Maigret adoption scan failed: {exc}"]
            )

        entities: list[Entity] = []
        edges: list[Edge] = []
        seen_profiles: set[tuple[str, str]] = set()
        found_count = 0

        for check in checks:
            if check.status != CLAIMED:
                continue
            platform = check.site.name
            dedupe_key = (platform.lower(), (check.profile_url or username).lower())
            if dedupe_key in seen_profiles:
                continue
            seen_profiles.add(dedupe_key)

            social_entity = Entity(
                type=EntityType.SOCIAL_MEDIA,
                value=f"{username}@{platform}",
                properties={
                    "platform": platform,
                    "username": username,
                    "profile_url": check.profile_url,
                    "status": check.status,
                    "check_type": check.site.check_type,
                    "http_status": check.http_status,
                    "engine": check.site.engine,
                    "tool": "maigret-adoption",
                    "database_source": "vendored_maigret_data_json",
                    "maigret_version": MAIGRET_VERSION,
                    "tags": check.site.tags,
                },
                source=self.name,
            )
            entities.append(social_entity)
            edges.append(
                Edge(
                    source_id=entity.id,
                    target_id=social_entity.id,
                    label="has account",
                    source_transform=self.name,
                )
            )

            if check.profile_url:
                url_entity = Entity(
                    type=EntityType.URL,
                    value=check.profile_url,
                    properties={
                        "platform": platform,
                        "username": username,
                        "tool": "maigret-adoption",
                    },
                    source=self.name,
                )
                entities.append(url_entity)
                edges.append(
                    Edge(
                        source_id=social_entity.id,
                        target_id=url_entity.id,
                        label="profile URL",
                        source_transform=self.name,
                    )
                )

            found_count += 1
            if found_count >= max_results:
                break

        messages.append(self._summary(checks, found_count))
        if found_count == 0:
            messages.append("No claimed profiles found.")

        return TransformResult(entities=entities, edges=edges, messages=messages)

    def _site_database(self) -> tuple[SiteDefinition, ...]:
        return load_sites(DATA_PATH)

    def _build_client(
        self, *, timeout_seconds: int, concurrency: int
    ) -> httpx.AsyncClient:
        return httpx.AsyncClient(
            timeout=httpx.Timeout(timeout_seconds),
            limits=httpx.Limits(
                max_connections=concurrency,
                max_keepalive_connections=max(concurrency // 2, 1),
            ),
        )

    async def _scan_sites(
        self,
        username: str,
        sites: list[SiteDefinition],
        *,
        timeout_seconds: int,
        concurrency: int,
    ) -> list[SiteCheck]:
        sem = asyncio.Semaphore(concurrency)
        async with self._build_client(
            timeout_seconds=timeout_seconds, concurrency=concurrency
        ) as client:
            return list(
                await asyncio.gather(
                    *(self._check_site(client, sem, site, username) for site in sites)
                )
            )

    async def _check_site(
        self,
        client: httpx.AsyncClient,
        sem: asyncio.Semaphore,
        site: SiteDefinition,
        username: str,
    ) -> SiteCheck:
        if not username_allowed(site, username):
            return SiteCheck(
                site=site,
                profile_url="",
                status=SKIPPED,
                reason="Unsupported username format",
            )

        rendered = render_urls(site, username)
        if rendered is None:
            return SiteCheck(
                site=site,
                profile_url="",
                status=UNKNOWN,
                reason="Unusable URL template",
            )
        profile_url, probe_url = rendered

        method = request_method(site)
        headers = {
            "User-Agent": DEFAULT_USER_AGENT,
            "Connection": "close",
            **site.headers,
        }
        payload_args: dict[str, JsonObject] = {}
        if method == "POST" and site.request_payload:
            payload = request_payload(site, username)
            if payload is None:
                return SiteCheck(
                    site=site,
                    profile_url=profile_url,
                    status=UNKNOWN,
                    reason="Unusable payload template",
                )
            is_form = headers.get("Content-Type") == "application/x-www-form-urlencoded"
            payload_args["data" if is_form else "json"] = payload

        async with sem:
            try:
                response = await client.request(
                    method,
                    probe_url,
                    headers=headers,
                    follow_redirects=site.check_type != "response_url",
                    **payload_args,
                )
            except httpx.TimeoutException:
                return SiteCheck(
                    site=site,
                    profile_url=profile_url,
                    status=UNKNOWN,
                    reason="Request timeout",
                )
            except Exception:
                return SiteCheck(
                    site=site,
                    profile_url=profile_url,
                    status=UNKNOWN,
                    reason="Request failed",
                )

        status, reason = evaluate_response(
            site, response.status_code, _decode_body(response, site, method)
        )
        return SiteCheck(
            site=site,
            profile_url=profile_url,
            status=status,
            http_status=response.status_code,
            reason=reason,
        )

    @staticmethod
    def _summary(checks: list[SiteCheck], found_count: int) -> str:
        statuses = Counter(check.status for check in checks)
        summary = (
            f"Scan summary: found={found_count}, not_found={statuses[AVAILABLE]}, "
            f"unknown={statuses[UNKNOWN]}, skipped={statuses[SKIPPED]}."
        )
        reasons = Counter(
            check.reason.split(":", 1)[0] for check in checks if check.status == UNKNOWN
        )
        if reasons:
            breakdown = ", ".join(
                f"{reason} {count}" for reason, count in reasons.most_common(4)
            )
            summary = f"{summary} Unknown because: {breakdown}."
        return summary

    @staticmethod
    def _normalize_input(entity: Entity) -> str:
        raw = str(entity.value or "").strip()
        if not raw:
            return ""
        if entity.type == EntityType.SOCIAL_MEDIA and "@" in raw:
            candidate = raw.split("@", 1)[0].strip()
            return candidate if USERNAME_RE.fullmatch(candidate) else ""
        if entity.type == EntityType.PERSON:
            candidate = raw.lower().replace(" ", "")
            return candidate if USERNAME_RE.fullmatch(candidate) else ""
        return raw if USERNAME_RE.fullmatch(raw) else ""

    @staticmethod
    def _parse_bool(raw: str | None, default: bool) -> bool:
        if raw is None:
            return default
        value = str(raw).strip().lower()
        if value in {"1", "true", "yes", "on"}:
            return True
        if value in {"0", "false", "no", "off"}:
            return False
        return default
